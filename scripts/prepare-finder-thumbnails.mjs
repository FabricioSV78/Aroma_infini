import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { format, resolveConfig } from 'prettier'
import sharp from 'sharp'

// Derive only the local family photographs currently used by the finder.
// Keep the full composition: CSS retains responsibility for the visible crop.
const root = process.cwd()
const imageDirectory = path.resolve(root, 'public/images')
const content = await readFile(
  path.join(root, 'src/content/fragrance-finder.ts'),
  'utf8',
)
const sources = [
  ...new Set(content.match(/\/images\/olfactory-[a-z0-9-]+\.webp/g) ?? []),
].sort()
if (!sources.length) throw new Error('No local finder photographs found.')

const widths = [160, 320]
const entries = []
const measurements = []
const sha256 = (buffer) => createHash('sha256').update(buffer).digest('hex')

for (const source of sources) {
  const originalPath = path.resolve(root, `public${source}`)
  if (path.dirname(originalPath) !== imageDirectory)
    throw new Error(`Unexpected finder source: ${source}`)
  const original = await readFile(originalPath)
  const originalHash = sha256(original)
  const metadata = await sharp(original).metadata()
  if (!metadata.width || metadata.width < Math.max(...widths))
    throw new Error(`Finder source is too small: ${source}`)

  const variants = []
  const measured = { source, originalBytes: original.length, variants: [] }
  for (const width of widths) {
    const url = source.replace(/\.webp$/, `-thumb-${width}.webp`)
    const targetPath = path.resolve(root, `public${url}`)
    if (
      targetPath === originalPath ||
      path.dirname(targetPath) !== imageDirectory
    )
      throw new Error(`Refusing to overwrite an original: ${targetPath}`)
    const derivative = await sharp(original)
      .resize({ width, fit: 'inside', withoutEnlargement: true })
      .webp({ quality: 92, effort: 6, smartSubsample: true })
      .toBuffer()
    await writeFile(targetPath, derivative)
    variants.push({ src: url, width })
    measured.variants.push({ src: url, width, bytes: derivative.length })
  }
  // Keep the original as the high-density option for larger quiz photographs.
  variants.push({ src: source, width: metadata.width })
  entries.push([source, variants])
  measurements.push(measured)
  if (sha256(await readFile(originalPath)) !== originalHash)
    throw new Error(`The original changed unexpectedly: ${source}`)
}

const manifest = `// Generated by scripts/prepare-finder-thumbnails.mjs. Originals stay unchanged.
export interface LocalImageVariant {
  readonly src: string
  readonly width: number
}

const localImageVariants: ReadonlyMap<string, readonly LocalImageVariant[]> =
  new Map<string, readonly LocalImageVariant[]>(${JSON.stringify(entries, null, 2)})

// Exact local keys only: uploads, remote URLs and unregistered assets fall back.
export function getLocalImageVariants(
  image: string,
): readonly LocalImageVariant[] | undefined {
  return localImageVariants.get(image)
}
`
const manifestPath = path.join(root, 'src/content/image-variants.ts')
await writeFile(
  manifestPath,
  await format(manifest, {
    ...(await resolveConfig(manifestPath)),
    filepath: manifestPath,
  }),
)
