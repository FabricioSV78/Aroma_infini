import sharp from 'sharp'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { format, resolveConfig } from 'prettier'

// Generate the four-card framing from original PNGs, never from resized WebPs.
const originals = JSON.parse(
  await readFile('scripts/discovery-assets.json', 'utf8'),
)
const accessory = JSON.parse(
  await readFile('scripts/category-complements-v1.json', 'utf8'),
)
const sources = [
  {
    id: 'hombre',
    name: 'discovery-bois',
    source: originals['discovery-bois'],
    x: 0.5,
    y: 0.56,
  },
  {
    id: 'mujer',
    name: 'discovery-petale',
    source: originals['discovery-petale'],
    x: 0.5,
    y: 0.5,
  },
  {
    id: 'unisex',
    name: 'discovery-libre',
    source: originals['discovery-libre'],
    x: 0.72,
    y: 0.5,
  },
  {
    id: 'complementos',
    name: accessory.asset,
    source: accessory.source,
    x: 0.5,
    y: 0.5,
  },
]
await mkdir('public/images', { recursive: true })
const manifest = {}
for (const { id, name, source, x, y } of sources) {
  const original = await sharp(source).metadata()
  const unit = Math.floor(Math.min(original.width / 4, original.height / 5))
  const width = unit * 4
  const height = unit * 5
  const region = {
    left: Math.round((original.width - width) * x),
    top: Math.round((original.height - height) * y),
    width,
    height,
  }
  const image = `${name}-category`
  const widths = [
    ...new Set(
      [320, 480, 640, 800, 960].filter((size) => size < width).concat(width),
    ),
  ]
  for (const size of widths) {
    await sharp(source)
      .extract(region)
      .resize({ width: size, withoutEnlargement: true })
      .webp({ quality: 90, smartSubsample: true, effort: 5 })
      .toFile(`public/images/${image}-${size}.webp`)
  }
  manifest[id] = { image, width, height, widths }
  console.log(
    `${id}: ${original.width}×${original.height} → ${width}×${height}; ${widths.join(', ')}w`,
  )
}
const manifestPath = 'src/content/category-images.ts'
const generated = `// Generated by scripts/prepare-category-images.mjs. Native 4:5 crops; no enlargement.\nexport const fourCategoryImages = ${JSON.stringify(manifest, null, 2)} as const\n`
await writeFile(
  manifestPath,
  await format(generated, {
    ...(await resolveConfig(manifestPath)),
    filepath: manifestPath,
  }),
)
